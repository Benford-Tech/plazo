/** Polish plural: 1 → one; 2–4 (not 12–14) → few; everything else (0, 5+, 12–14…) → many. */
function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const d = n % 10;
  const h = n % 100;
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return few;
  return many;
}

