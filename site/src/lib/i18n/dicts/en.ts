const enDays = (days: number) => `${days} day${days === 1 ? "" : "s"}`;

/** "1st", "2nd", "3rd", "4th", "11th"… */
const ordinal = (n: number) => {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${n}th`;
  switch (n % 10) {
    case 1:
      return `${n}st`;
    case 2:
      return `${n}nd`;
    case 3:
      return `${n}rd`;
    default:
      return `${n}th`;
  }
};

