import { crc32, deflateRawSync } from 'zlib';
import { Service } from 'typedi';
import { PLUGIN_FILES } from '@/wordpress/plugin-files.generated';

/**
 * The WordPress plugin « Plazo » as a .zip, built on request from its files (wordpress-plugin/plazo, copied into
 * plugin-files.generated.ts): one folder `plazo/`, deflated entries, what Extensions › Téléverser expects.
 */
@Service()
export class WordpressPluginService {
  public static readonly VERSION = (PLUGIN_FILES['plazo.php'].match(/^ \* Version: (\S+)$/m) ?? [])[1] ?? '1.0.0';
  private cached: Buffer | null = null;

  public zip(): Buffer {
    if (!this.cached) this.cached = buildZip(Object.entries(PLUGIN_FILES).map(([path, text]) => [`plazo/${path}`, Buffer.from(text, 'utf8')]));
    return this.cached;
  }
}

/** A plain ZIP (PKZIP 2.0, deflate, no extra fields): local headers, data, central directory, end record. */
export function buildZip(entries: [string, Buffer][], date = new Date('2026-11-19T12:00:00Z')): Buffer {
  const dosTime = (date.getUTCHours() << 11) | (date.getUTCMinutes() << 5) | (date.getUTCSeconds() >> 1);
  const dosDate = ((date.getUTCFullYear() - 1980) << 9) | ((date.getUTCMonth() + 1) << 5) | date.getUTCDate();
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const [name, data] of entries) {
    const nameBytes = Buffer.from(name, 'utf8');
    const compressed = deflateRawSync(data);
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(8, 8); // deflate
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBytes, compressed);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBytes);
    offset += local.length + nameBytes.length + compressed.length;
  }
  const directory = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
